import { cp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { publishEditorial } from './publish-editorial.mjs';
const root = resolve(import.meta.dirname, '..');
execFileSync('python3', [resolve(root,'scripts/import-editions.py'), '--rebuild-indexes'], {cwd:root,stdio:'inherit'});
execFileSync('python3', [resolve(root,'scripts/import-editions.py'), '--verify'], {cwd:root,stdio:'inherit'});
const editorial = await publishEditorial({root});
const manifest = JSON.parse(await readFile(resolve(root, 'data/manifest.json'), 'utf8'));
if (!manifest.books?.length || !manifest.edition?.name) throw new Error('A validated source corpus is required before building.');
await rm(resolve(root,'public/data'),{recursive:true,force:true});
await mkdir(resolve(root, 'public/data'), { recursive:true });
await cp(resolve(root, 'data'), resolve(root, 'public/data'), { recursive:true, filter: path => !/\.(zip|usfm|usx|xml)$/i.test(path) && path !== resolve(root,'data/editorial-published.json') });
const {totalSourceUnits,remainingSourceUnits,candidateCount} = editorial.backlog;
await writeFile(resolve(root,'public/data/editorial.json'),JSON.stringify({schemaVersion:1,editionId:editorial.editionId,approvedComparisons:editorial.approvedComparisons,approvedParaphrases:editorial.approvedParaphrases,approvedContent:editorial.approvedContent,coverage:editorial.coverage.filter(row=>row.status!=='unreviewed'),coverageCounts:editorial.coverageCounts,backlog:{totalSourceUnits,remainingSourceUnits,candidateCount}})+'\n');
await mkdir(resolve(root, 'public/docs'), { recursive:true });
const spec = await readFile(resolve(root, 'docs/specs/Adigun-AiBible_Codex_Master_Prompt.md'), 'utf8');
await writeFile(resolve(root, 'public/docs/Adigun-AiBible_Codex_Master_Prompt.txt'), spec);
console.log(`Prepared ${manifest.books.length} source books and the complete specification for the static build.`);
